def create_project(folder, seconds=60, fps=30, samples=12):
    folder = Path(folder).resolve()
    require(not (folder/'project.json').exists(), 'Project already exists; choose a new folder')
    require(isinstance(fps,int) and 8<=fps<=60 and 2<=seconds<=600 and round(seconds*fps)==seconds*fps,
            'Demo requires 2–600 frame-aligned seconds and 8–60 FPS')
    folder.mkdir(parents=True, exist_ok=True); assets = folder/'assets'; assets.mkdir(exist_ok=True)
    save(assets/'light-study.png', width=640, height=360, samples=samples, seed=22, bounces=5)
    procedural_score(assets/'original-score.wav', seconds)
    copy = [
      (5,'LA PREGUNTA','Una idea.\nUna prueba.','¿Qué entrega realmente la tecnología?',['Persona','Evidencia'],'Beneficios que se pueden explicar'),
      (8,'MANUSCRITO I','La evidencia\nes el punto de partida.','Cada afirmación conserva su fuente y su alcance.',['Fuente','Afirmación','Guion'],'Las hipótesis tienen una etiqueta'),
      (8,'MANUSCRITO II','El movimiento\ntambién cuenta.','Una curva suave guía la mirada y conserva la continuidad.',['Inicio','Recorrido','Encuadre'],'Cámara con interpolación minimum jerk'),
      (6,'MANUSCRITO III','La luz\nconstruye materia.','Sombras, rebotes difusos y reflejos en un render físico de referencia.',[],'Render CPU • geometría de esferas'),
      (9,'MANUSCRITO IV','Una voz\ncon identidad.','Voz grabada o síntesis opcional. Música que cede espacio a la narración.',['Voz','Mezcla','Escucha'],'El acento costeño requiere audición'),
      (7,'LA MARCA','Un lenguaje\nvisual coherente.','Color, jerarquía y composición al servicio de una idea.',['Grafito','Turquesa','Oro'],'Paleta editable por el equipo de marca'),
      (11,'MANUSCRITO V','La calidad\nse comprueba.','Frames, duración, audio y trazabilidad. La revisión humana completa la entrega.',['Pruebas','Revisión','Entrega'],'56 perfiles con criterios de revisión'),
      (6,'GOTOGYM / QUANTUM COACH','Entender\npara avanzar.','Prototipo audiovisual. Sustituye esta demostración por tecnologías y pruebas verificadas.',[],'De la evidencia a una historia de 60 s'),
    ]
    shots=[]; end=0; accumulated=0; total=round(seconds*fps)
    for i,(span,eyebrow,title,body,nodes,card) in enumerate(copy):
        accumulated += span; stop=round(accumulated/60*total)/fps
        shots.append(dict(start=end,end=stop,kind='image',asset='assets/light-study.png',
                          title=title,body=body,eyebrow=eyebrow,nodes=nodes,card=card,
                          focus={'vertical':[.45 if i%2 else .65,.48],'horizontal':[.5,.5]},
                          zoom=[1.02,1.10] if i%2==0 else [1.10,1.02],
                          claim_ids=['prototype'], evidence_required=True));end=stop
    rights={}
    for name in ['light-study.png','original-score.wav']:
        rights['assets/'+name]={'origin':'Original procedural fixture generated by this project',
                               'rights':'Project owner; no third-party footage or voice',
                               'sha256':sha256(assets/name)}
    m={'schema':'qaf_video_project_v1','title':'GoToGym · Del rigor a la imagen',
       'duration':seconds,'fps':fps,'mode':'conceptual',
       'label':'PROTOTIPO AUDIOVISUAL • DEMOSTRACIÓN CONCEPTUAL',
       'color_pipeline':'srgb_preview','shots':shots,
       'music':'assets/original-score.wav','subtitles':[],
       'claims':{'prototype':{'status':'conceptual','source':'docs/IMPLEMENTACION.md',
                            'scope':'Audiovisual reference implementation; not product efficacy or clinical claims'}},
       'assets':rights,'reviews':{},'brand_colors':json.loads((ASSETS/'brand.json').read_text())['colors']}
    atomic_json(folder/'project.json',m)
    (folder/'narration-es.txt').write_text(NARRATION+'\n',encoding='utf-8')
    return folder/'project.json'
